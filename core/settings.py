# Sprint 4: configuração por ambiente. O .env fica fora do git, e na publicação os
# valores chegam pelas variáveis de ambiente do servidor. `load_dotenv` não sobrescreve
# variável que já exista no processo, então o servidor sempre tem a palavra final.
load_dotenv(BASE_DIR / '.env')


def env(nome, padrao=None):
    """Devolve a variável de ambiente, ou o padrão quando ela não existe."""
    return os.environ.get(nome, padrao)


def env_list(nome, padrao=''):
    """Lê uma variável separada por vírgula e devolve a lista sem item vazio."""
    bruto = os.environ.get(nome, padrao)
    return [item.strip() for item in bruto.split(',') if item.strip()]


def env_bool(nome, padrao=False):
    """Interpreta 1, true, yes ou on como verdadeiro."""
    valor = os.environ.get(nome)
    if valor is None:
        return padrao
    return valor.strip().lower() in ('1', 'true', 'yes', 'on')


